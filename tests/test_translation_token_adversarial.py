"""Adversarial test suite for Machine Translation (Google Translate, DeepL, LLMs) token preservation.

Validates that token sanitizers and placeholder validators withstand real-world MT deformations:
1. Tag casing variations (<B0></B0>, <B1> </B1>).
2. Spacing inside tag syntax (< b0 > < / b0 >, <b 0> </b 0>).
3. Consecutive duplicate tags generated by NMT (<b0><b0></b0>).
4. Attached punctuation, parentheses, and quotes (e.g. « <b0></b0> », (<b0></b0>).).
5. Mangled syntax (<b0></b>, <b0/>, <b>0></b>).
6. FormulaIsolator.restore_translation roundtrip recovery without falling back to source text.
"""

from __future__ import annotations

import unittest
from layoutlingua.core.ir import GlyphSpan, TextBlock
from layoutlingua.processing.formula.isolator import FormulaIsolator
from layoutlingua.processing.formula.models import FormulaToken, TextSegment
from layoutlingua.translation.google_rpc import _sanitize_translated_tokens


class TestTranslationTokenAdversarial(unittest.TestCase):
    """Test suite ensuring zero translation fallback and 100% token restoration under MT corruption."""

    def setUp(self) -> None:
        self.isolator = FormulaIsolator()

    # -------------------------------------------------------------------------
    # 1. Adversarial MT Token Sanitization Tests
    # -------------------------------------------------------------------------

    def test_sanitize_casing_variations(self) -> None:
        """Capitalized tags like <B0></B0> or <B1> </B1> must be normalized to lowercase <bN></bN>."""
        corrupted = "Theo công thức <B0></B0> và định lý <B1> </B1> ta có kết quả."
        sanitized = _sanitize_translated_tokens(corrupted)
        self.assertIn("<b0></b0>", sanitized)
        self.assertIn("<b1></b1>", sanitized)
        self.assertNotIn("<B0>", sanitized)
        self.assertNotIn("<B1>", sanitized)

    def test_sanitize_spacing_inside_tag_syntax(self) -> None:
        """Stray spaces inserted inside XML brackets by MT engines must be resolved."""
        corrupted = (
            "Giá trị của < b0 > < / b0 > tương đương với <  b1  ></  b1  > "
            "khi xét trong không gian metric."
        )
        sanitized = _sanitize_translated_tokens(corrupted)
        self.assertIn("<b0></b0>", sanitized)
        self.assertIn("<b1></b1>", sanitized)

    def test_sanitize_duplicate_consecutive_tags(self) -> None:
        """NMT engines often duplicate tags (e.g. <b0><b0></b0> or <b0></b0><b0></b0>). Must collapse to 1."""
        corrupted = "Công thức <b0><b0></b0> và <b1></b1><b1></b1> được áp dụng."
        sanitized = _sanitize_translated_tokens(corrupted)
        self.assertEqual(sanitized.count("<b0></b0>"), 1)
        self.assertEqual(sanitized.count("<b1></b1>"), 1)

    def test_sanitize_mangled_closing_syntax(self) -> None:
        """Mangled tags like <b>0></b> or <b0></b> or <b0/> must be repaired to <b0></b0>."""
        cases = [
            ("Công thức <b>0></b> cho kết quả", "<b0></b0>"),
            ("Công thức <b0></b> cho kết quả", "<b0></b0>"),
            ("Công thức <b0/> cho kết quả", "<b0></b0>"),
        ]
        for corrupted, expected_token in cases:
            sanitized = _sanitize_translated_tokens(corrupted)
            self.assertIn(expected_token, sanitized, f"Failed to sanitize: {corrupted}")

    def test_sanitize_attached_punctuation_and_quotes(self) -> None:
        """Punctuation attached to placeholders must not corrupt tag boundaries."""
        corrupted = "Xét quan hệ (<b0></b0>), định lý «<b1></b1>», và kết quả <b2></b2>."
        sanitized = _sanitize_translated_tokens(corrupted)
        self.assertIn("<b0></b0>", sanitized)
        self.assertIn("<b1></b1>", sanitized)
        self.assertIn("<b2></b2>", sanitized)

    # -------------------------------------------------------------------------
    # 2. End-to-End Isolator Roundtrip Recovery Tests
    # -------------------------------------------------------------------------

    def test_roundtrip_restore_translation_with_corrupted_response(self) -> None:
        """Verify FormulaIsolator.restore_translation successfully restores math even with MT corruption."""
        # Source segment with two formula tokens: sin(x) and cos(x)
        token0 = FormulaToken(token_id=0, placeholder="<b0></b0>", raw_content="sin(x)", bbox=(0,0,10,10), font_name="CMMI10")
        token1 = FormulaToken(token_id=1, placeholder="<b1></b1>", raw_content="cos(x)", bbox=(0,0,10,10), font_name="CMMI10")
        segment = TextSegment(
            segment_id="seg_adv_1",
            raw_text="Cho hàm số sin(x) và cos(x) liên tục.",
            masked_text="Cho hàm số <b0></b0> và <b1></b1> liên tục.",
            tokens=[token0, token1],
        )

        # Corrupted MT response from real Google Translate behavior
        corrupted_mt_responses = [
            "Given the continuous functions <B0></B0> and <B1></B1>.",
            "Given the continuous functions < b0 > < / b0 > and < b1 > </ b1 >.",
            "Given the continuous functions <b0><b0></b0> and <b1></b1>.",
            "Given the continuous functions (<b0></b0>) and <b1></b1>.",
        ]

        for resp in corrupted_mt_responses:
            sanitized = _sanitize_translated_tokens(resp)
            clean_translated = self.isolator.normalize_placeholders(sanitized)
            restored = self.isolator.restore_translation(segment, clean_translated)

            # Restored text must contain both original math expressions
            self.assertIn("sin(x)", restored, f"Failed for MT response: {resp}")
            self.assertIn("cos(x)", restored, f"Failed for MT response: {resp}")
            # Restored text must NEVER leak raw placeholder tokens
            self.assertNotIn("<b0>", restored)
            self.assertNotIn("<b1>", restored)
            self.assertNotIn("⟦VT_", restored)
            # Restored text must be English (not fallen back to Vietnamese)
            self.assertIn("Given", restored)


if __name__ == "__main__":
    unittest.main()
